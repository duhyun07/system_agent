"""Scaffolding for a local kernelCTF crash-reproduction / debugging environment.

`scaffold()` is a pure function: it returns a map of {relative path -> text
content}. It performs no I/O and no network access. The CLI writes the returned
files through the guarded `atomic_write` path (workspace-only, protected-path
rejection, no symlinks, refuse-overwrite-by-default).

What the generated environment is: a *local* QEMU VM to boot an authorized
kernelCTF target kernel and reproduce a crash for triage. What it is NOT: this
module never downloads a kernel, never builds one, never runs the VM, and never
produces exploit code. The researcher obtains the official release artifacts,
reviews the generated scripts, and runs the VM themselves.
"""
from __future__ import annotations

import json
from datetime import date

from core.programs import Program

# Files that should be marked executable after writing.
EXECUTABLE: tuple[str, ...] = ("run-qemu.sh", "scripts/attach-gdb.sh")


def _run_qemu_sh(instance: str) -> str:
    return f"""#!/usr/bin/env bash
# Local kernelCTF repro VM ({instance} instance). Review before running.
# System Agent generated this script; it does not run it for you. It boots a
# kernel YOU provide (from the official kernelCTF release) in QEMU for local
# crash reproduction and debugging. It downloads nothing.
set -euo pipefail

here="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
BZIMAGE="${{BZIMAGE:-$here/artifacts/bzImage}}"
ROOTFS="${{ROOTFS:-$here/artifacts/rootfs.img}}"
MEM="${{MEM:-4G}}"
SMP="${{SMP:-2}}"
# KASLR: off by default for debugging. The real instance runs with KASLR on;
# set KASLR=1 to match it once your repro is stable.
KASLR="${{KASLR:-0}}"
# GDB=1 opens a gdb stub on tcp::1234; GDBWAIT=1 also freezes the CPU at boot
# until you attach (see scripts/attach-gdb.sh).
GDB="${{GDB:-0}}"
GDBWAIT="${{GDBWAIT:-0}}"

for f in "$BZIMAGE" "$ROOTFS"; do
  if [[ ! -f "$f" ]]; then
    echo "missing artifact: $f" >&2
    echo "Obtain the official release artifacts first — see FETCH.md." >&2
    exit 1
  fi
done

append="console=ttyS0 root=/dev/ram oops=panic panic=1"
if [[ "$KASLR" != "1" ]]; then append+=" nokaslr"; fi

qemu_args=(
  -m "$MEM" -smp "$SMP"
  -kernel "$BZIMAGE"
  -initrd "$ROOTFS"
  -append "$append"
  -cpu qemu64,+smep,+smap
  -nographic -no-reboot
)
if [[ "$GDB" == "1" || "$GDBWAIT" == "1" ]]; then qemu_args+=(-gdb tcp::1234); fi
if [[ "$GDBWAIT" == "1" ]]; then qemu_args+=(-S); fi

echo "booting ${{BZIMAGE##*/}} ({instance}); KASLR=$KASLR GDB=$GDB GDBWAIT=$GDBWAIT" >&2
exec qemu-system-x86_64 "${{qemu_args[@]}}"
"""


def _attach_gdb_sh() -> str:
    return """#!/usr/bin/env bash
# Attach gdb to the QEMU stub started by run-qemu.sh with GDB=1 (or GDBWAIT=1).
# Point VMLINUX at the uncompressed vmlinux that matches the bzImage you booted.
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VMLINUX="${VMLINUX:-$here/../artifacts/vmlinux}"
if [[ ! -f "$VMLINUX" ]]; then
  echo "missing $VMLINUX (uncompressed vmlinux with symbols); set VMLINUX=..." >&2
  exit 1
fi
exec gdb -q "$VMLINUX" \
  -ex 'set architecture i386:x86-64' \
  -ex 'target remote :1234'
"""


def _readme(program: Program, instance: str, source: str, dest_rel: str) -> str:
    spec = program.instances.get(instance, {})
    focus = spec.get("config_focus", []) or []
    focus_md = "\n".join(f"  - {item}" for item in focus) or "  - (see the official .config)"
    rules = program.links.get("official_rules", "the kernelCTF rules page")
    release = program.artifacts.get("release_page", "the official kernelCTF release")
    return f"""# kernelCTF local repro environment — {instance} instance

Generated by System Agent for authorized kernelCTF research. This directory is a
**local crash-reproduction and debugging** setup for the `{instance}` target.

> System Agent generated review-ready text only. It did **not** download a
> kernel, build one, run the VM, or produce any exploit. You obtain the official
> release artifacts, review these scripts, and run the VM yourself, under the
> kernelCTF rules: {rules}

- Instance: **{instance}** — {spec.get('description', '')}
- Kernel: {spec.get('kernel', 'see the release')}
- Source tree for triage/report: `{source}`
- Config focus to confirm against the official `.config`:
{focus_md}

## Workflow

1. **Get the official artifacts.** Follow [FETCH.md](FETCH.md) to download the
   `{instance}` release's `bzImage`, `.config`, rootfs, and `metadata.json` from
   {release}, and verify the checksums. Put them under `artifacts/`.
2. **Boot the VM.** Review then run `./run-qemu.sh`. Use `GDB=1 ./run-qemu.sh`
   and `scripts/attach-gdb.sh` for kernel debugging.
3. **Reproduce the crash** and save the console/KASAN output to `notes/`.
4. **Triage from source** with the same checkout this env records:

   ```bash
   system-agent triage {program.key} --source {source} \\
     --crash {dest_rel}/notes/crash.log --task '...'
   ```

5. **Draft the report:**

   ```bash
   system-agent report build {program.key} --fields-file {dest_rel}/notes/fields.json \\
     > {dest_rel}/notes/report.md
   ```

See [`env.json`](env.json) for the machine-readable manifest.
"""


def _fetch_md(program: Program, instance: str) -> str:
    artifacts = program.artifacts
    files = artifacts.get("files", []) or []
    files_md = "\n".join(f"- `{name}`" for name in files) or "- (see the release directory)"
    return f"""# Obtaining the official {instance} artifacts

System Agent does **not** fetch these for you. Download them yourself from the
official kernelCTF release and verify the checksums before using them.

- Release listing: {artifacts.get('release_page', 'official kernelCTF release')}
- {artifacts.get('note', '')}

Place these under `artifacts/` in this directory:

{files_md}

Checklist:

- [ ] Downloaded the `{instance}` release's artifacts from the official source.
- [ ] Verified each file against the checksums in `metadata.json`.
- [ ] Noted the exact source commit from `metadata.json` and checked out that
      commit in the source tree used for `triage`/`report`.
- [ ] (Optional) Built/obtained an uncompressed `vmlinux` with symbols for gdb.

> Treat downloaded artifacts as untrusted: keep them in `artifacts/`, run the VM
> on a machine/account you are willing to expose, and do not run the images
> outside the VM.
"""


def _config_notes(program: Program, instance: str) -> str:
    spec = program.instances.get(instance, {})
    focus = spec.get("config_focus", []) or []
    focus_md = "\n".join(f"- {item}" for item in focus) or "- (see the official .config)"
    return f"""# {instance} config notes

The authoritative configuration is the `.config` shipped in the official release
(see FETCH.md). These are areas to confirm when you read it:

{focus_md}

To compare the official config with a config you build from the source tree:

```bash
# from your kernel source checkout
scripts/diffconfig <(cat artifacts/.config) .config   # or: diff the two files
```

If you rebuild the kernel to add debug options (e.g. CONFIG_GDB_SCRIPTS,
CONFIG_DEBUG_INFO), keep the instance's security-relevant options unchanged so
your repro still matches the target.
"""


def _notes_placeholder(program: Program) -> str:
    fields = ",\n  ".join(f'"{name}": ""' for name in program.report_fields)
    return (
        "# Triage notes\n\n"
        "Paste the reproduced crash output into `crash.log` in this folder, then run\n"
        f"`system-agent triage {program.key} --source <this env's source> --crash "
        "notes/crash.log`.\n\n"
        "Fill `fields.json` as you confirm each item from source, then\n"
        f"`system-agent report build {program.key} --fields-file notes/fields.json`.\n"
    ), "{\n  " + fields + "\n}\n"


def _gitignore() -> str:
    return (
        "# Untrusted / large artifacts obtained from the official release.\n"
        "artifacts/\n"
        "notes/crash.log\n"
    )


def scaffold(program: Program, instance: str, *, source: str, dest_rel: str) -> dict[str, str]:
    """Return {relative path -> content} for a kernelCTF repro environment.

    Raises ValueError if the program has no such instance.
    """
    if instance not in program.instances:
        known = ", ".join(program.instances) or "(none configured)"
        raise ValueError(f"Unknown instance '{instance}' for {program.key}. Configured instances: {known}")
    triage_note, fields_json = _notes_placeholder(program)
    manifest = {
        "program": program.key,
        "program_name": program.name,
        "instance": instance,
        "source": source,
        "created": date.today().isoformat(),
        "official_rules": program.links.get("official_rules", ""),
        "release_page": program.artifacts.get("release_page", ""),
        "generated_by": "system-agent env init",
        "note": "Local repro scaffolding only. No kernel is downloaded, built, or run by System Agent.",
    }
    return {
        "README.md": _readme(program, instance, source, dest_rel),
        "FETCH.md": _fetch_md(program, instance),
        "run-qemu.sh": _run_qemu_sh(instance),
        "scripts/attach-gdb.sh": _attach_gdb_sh(),
        "config/notes.md": _config_notes(program, instance),
        "notes/triage.md": triage_note,
        "notes/fields.json": fields_json,
        ".gitignore": _gitignore(),
        "env.json": json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
    }
